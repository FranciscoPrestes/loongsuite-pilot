import type { AgentDefinition } from '../types/deployment.js';
import { listCapabilities, type CapabilityManifest } from './capabilities.js';

export const MATRIX_PLATFORMS = ['darwin', 'linux', 'win32'] as const;
export const MATRIX_CAPABILITIES = ['messages', 'tools', 'results', 'tokens', 'subagents'] as const;
type Platform = typeof MATRIX_PLATFORMS[number];
type Capability = typeof MATRIX_CAPABILITIES[number];
/** contract_validated != live_validated: only recorded rehearsal evidence earns the latter. */
export type MatrixStatus = 'contract_validated' | 'live_validated' | 'declared_conditional' | 'not_exposed' | 'unavailable';

export interface LiveEvidence { harnessId: string; platform: Platform; capability: Capability; evidenceId: string }
export interface MatrixRow {
  harnessId: string; displayName: string; platform: Platform; versionRange: string; lifecycle: string;
  capability: Capability; status: MatrixStatus;
}
export interface CapabilityMatrix { ids: string[]; rows: MatrixRow[] }

const EVENT_CLASS: Partial<Record<Capability, string>> = { messages: 'message', tools: 'tool_call', results: 'tool_result', tokens: 'llm_usage' };

function statusOf(m: CapabilityManifest, platform: Platform, capability: Capability, evidence: readonly LiveEvidence[]): MatrixStatus {
  const support = m.capabilities[capability];
  if (!m.platforms.includes(platform) || m.lifecycle === 'retired' || m.lifecycle === 'unavailable' || support === 'unavailable') return 'unavailable';
  const eventClass = EVENT_CLASS[capability];
  if (eventClass && !m.sourceRules.some(r => r.eventClass === eventClass)) return 'not_exposed';
  if (evidence.some(e => e.harnessId === m.harnessId && e.platform === platform && e.capability === capability)) return 'live_validated';
  return support === 'validated' ? 'contract_validated' : 'declared_conditional';
}

/** One row per manifest x platform x capability, ordered deterministically. */
export function buildCapabilityMatrix(definitions: readonly AgentDefinition[], evidence: readonly LiveEvidence[] = []): CapabilityMatrix {
  const manifests = listCapabilities(definitions).sort((a, b) => a.harnessId.localeCompare(b.harnessId));
  const rows = manifests.flatMap(m => MATRIX_PLATFORMS.flatMap(platform => MATRIX_CAPABILITIES.map((capability): MatrixRow => ({
    harnessId: m.harnessId, displayName: m.displayName, platform, versionRange: m.versionRange ?? 'unspecified',
    lifecycle: m.lifecycle, capability, status: statusOf(m, platform, capability, evidence),
  }))));
  return { ids: manifests.map(m => m.harnessId), rows };
}

const LABEL: Record<MatrixStatus, string> = {
  contract_validated: 'contract validated', live_validated: 'live validated', declared_conditional: 'declared, live pending',
  not_exposed: 'not exposed', unavailable: 'unavailable',
};

/** Markdown (English, local UI language) generated from the loaded definitions. */
export function generateCapabilityMatrix(definitions: readonly AgentDefinition[], evidence: readonly LiveEvidence[] = []): string {
  const matrix = buildCapabilityMatrix(definitions, evidence);
  const manifests = new Map(listCapabilities(definitions).map(m => [m.harnessId, m]));
  const lines = [
    '# Analytics capability matrix', '',
    '<!-- Generated by scripts/generate-analytics-capabilities.mjs; do not edit by hand. -->', '',
    'Statuses: `contract validated` (fixtures/contract tests only), `live validated` (recorded real-harness rehearsal), ' +
    '`declared, live pending` (declared by the manifest, no live proof yet), `not exposed` (no source rule), `unavailable`.', '',
    'Contract tests are not live proof: a harness/OS without recorded rehearsal evidence stays pending.', '',
  ];
  for (const id of matrix.ids) {
    const m = manifests.get(id)!;
    lines.push(`## \`${id}\` (${m.displayName})`, '',
      `Lifecycle: ${m.lifecycle}. Version range: ${m.versionRange ?? 'unspecified'}. Mechanisms: ${m.mechanisms.join(', ')}.`, '',
      `| Platform | ${MATRIX_CAPABILITIES.join(' | ')} |`, `| --- | ${MATRIX_CAPABILITIES.map(() => '---').join(' | ')} |`);
    for (const platform of MATRIX_PLATFORMS) {
      const cells = MATRIX_CAPABILITIES.map(c => LABEL[matrix.rows.find(r => r.harnessId === id && r.platform === platform && r.capability === c)!.status]);
      lines.push(`| ${platform} | ${cells.join(' | ')} |`);
    }
    lines.push('', ...m.gaps.map(g => `- Gap: ${g}`), '');
  }
  return lines.join('\n');
}
